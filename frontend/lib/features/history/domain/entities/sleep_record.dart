class SleepRecord {
  final String date;
  final String quality;
  final String duration;
  final String score;
  final String awakenings;
  final String heartRate;
  final String note;

  const SleepRecord({
    required this.date,
    required this.quality,
    required this.duration,
    required this.score,
    required this.awakenings,
    required this.heartRate,
    required this.note,
  });
}
